test('insert and replace:', function (t) {
  const str = 'a irmã dorme'
  t.equal(nlp(str).match('irmã').insertBefore('minha').all().text(), 'a minha irmã dorme', here + 'insertBefore')
  t.equal(nlp(str).match('irmã').prepend('minha').all().text(), 'a minha irmã dorme', here + 'prepend')
  t.equal(nlp(str).match('irmã').insertAfter('pequena').all().text(), 'a irmã pequena dorme', here + 'insertAfter')
  t.equal(nlp(str).match('irmã').append('pequena').all().text(), 'a irmã pequena dorme', here + 'append')
  t.equal(nlp(str).match('irmã').insert('pequena').all().text(), 'a irmã pequena dorme', here + 'insert')
  t.equal(nlp(str).replace('irmã', 'mãe').all().text(), 'a mãe dorme', here + 'replace')
  t.equal(nlp(str).replace('irmã', 'avó paterna').all().text(), 'a avó paterna dorme', here + 'replace with two words')
  t.equal(nlp(str).match('irmã').replaceWith('criança').all().text(), 'a criança dorme', here + 'replaceWith')
  t.equal(nlp('a irmã dorme. a irmã come.').replace('irmã', 'mãe').all().text(), 'a mãe dorme. a mãe come.', here + 'replace every match')
  t.equal(nlp('Onde está a irmã?').replace('irmã', 'mãe').all().text(), 'Onde está a mãe?', here + 'replace keeps the question mark')
  t.equal(nlp('Olá irmã!').replace('olá', 'Adeus').all().text(), 'Adeus irmã!', here + 'replace the first word')
  t.equal(nlp('a irmã pequena dorme').remove('pequena').text(), 'a irmã dorme', here + 'remove')
  t.equal(nlp('a irmã pequena dorme').delete('pequena').text(), 'a irmã dorme', here + 'delete')
  t.equal(nlp('a irmã pequena dorme').match('pequena').remove().all().text(), 'a irmã dorme', here + 'remove self')
  t.equal(nlp('A irmã dorme.').concat('O irmão também.').length, 2, here + 'concat')
  // the original doc is changed too
  const doc = nlp(str)
  doc.match('irmã').replaceWith('mãe')
  t.equal(doc.text(), 'a mãe dorme', here + 'replaceWith mutates')
  // new words are parsed, too
  t.deepEqual(nlp('tenho cães').match('cães').insertBefore('três').all().numbers().get(), [3], here + 'an inserted number')
  t.deepEqual(nlp('tenho três cães').replace('três', 'dezessete').all().numbers().get(), [17], here + 'a replaced number')
  t.end()
})

test('whitespace and punctuation:', function (t) {
  const str = 'a irmã dorme'
  t.equal(nlp('  a irmã  ').trim().text(), 'a irmã', here + 'trim')
  t.equal(nlp(str).hyphenate().text(), 'a-irmã-dorme', here + 'hyphenate')
  t.equal(nlp(str).match('irmã').toQuotations().all().text(), 'a "irmã" dorme', here + 'toQuotations')
  t.equal(nlp(str).match('irmã').toQuotations('«', '»').all().text(), 'a «irmã» dorme', here + 'portuguese quotes')
  t.equal(nlp(str).match('irmã').toParentheses().all().text(), 'a (irmã) dorme', here + 'toParentheses')
  t.equal(nlp(str).match('irmã').pre('~').all().text(), 'a ~irmã dorme', here + 'pre')
  t.equal(nlp(str).match('dorme').post('!').all().text(), 'a irmã dorme!', here + 'post')
  t.equal(nlp('«Ficamos aqui.»').terms().length, 2, here + 'quotes are not terms')
  t.equal(nlp('«Ficamos aqui.»').match('^ficamos aqui$').found, true, here + 'guillemets are punctuation')
  t.equal(nlp('«Ficamos aqui.»').text(), '«Ficamos aqui.»', here + 'quotes survive')
  t.equal(nlp('Nós (ou seja eu) vamos').match('eu').text(), 'eu', here + 'parentheses are punctuation')
  t.equal(nlp('Vens? Claro que sim!').length, 2, here + '? and ! end a sentence')
  t.equal(nlp('— Vens? — perguntou ela.').match('vens').found, true, here + 'a dialogue dash')
  t.end()
})

test('tags:', function (t) {
  const doc = nlp('o sabiá dorme')
  doc.match('sabiá').tag('Ave')
  t.equal(doc.match('#Ave').text(), 'sabiá', here + 'a new tag')
  doc.match('sabiá').unTag('Ave')
  t.equal(doc.has('#Ave'), false, here + 'unTag')
  doc.match('sabiá').tag('#Person')
  t.equal(doc.has('#Person'), true, here + 'tag with a hash')
  t.equal(doc.match('sabiá').has('#Noun'), true, here + 'a Person is a Noun')
  doc.match('sabiá').tag('Verb')
  t.equal(doc.match('sabiá').has('#Noun'), false, here + 'Verb removes Noun')
  const d = nlp('o sabiá dorme')
  d.match('sabiá').tag('Noun').tagSafe('Verb')
  t.equal(d.match('sabiá').has('#Verb'), false, here + 'tagSafe does not over-write')
  t.equal(d.match('sabiá').has('#Noun'), true, here + 'tagSafe keeps the noun')
  t.equal(nlp('três cães').match('três').canBe('Verb').found, false, here + 'a value cannot be a verb')
  t.equal(nlp('três cães').match('três').canBe('Cardinal').found, true, here + 'a value can be a cardinal')
  // tags by their portuguese names
  t.equal(nlp('três cães').match('#Número').text(), 'três', here + 'a portuguese tag name')
  t.end()
})

test('loops:', function (t) {
  const doc = nlp(txt)
  const arr = []
  doc.forEach(s => arr.push(s.wordCount()))
  t.deepEqual(arr, [6, 4, 2], here + 'forEach')
  t.deepEqual(doc.map(s => ({ words: s.wordCount() }), []), [{ words: 6 }, { words: 4 }, { words: 2 }], here + 'map to an array')
  t.equal(doc.map(s => s.terms().first()).out('array').join(' '), 'A Onde Que', here + 'map to a view')
  t.equal(doc.filter(s => s.has('lições')).text(), 'Onde estão as lições?', here + 'filter')
  t.equal(doc.find(s => s.has('emoção')).text(), 'Que emoção!', here + 'find')
  t.equal(doc.some(s => s.has('lições')), true, here + 'some')
  t.equal(doc.some(s => s.has('cavalo')), false, here + 'some - none')
  t.equal(doc.random(1).length, 1, here + 'random')
  t.equal(doc.terms().random(3).length, 3, here + 'random 3')
  t.end()
})

test('clone:', function (t) {
  const doc = nlp('a irmã dorme')
  const copy = doc.clone()
  copy.replace('irmã', 'mãe')
  copy.match('dorme').tag('Foo')
  t.equal(doc.text(), 'a irmã dorme', here + 'original text is untouched')
  t.equal(copy.text(), 'a mãe dorme', here + 'clone is changed')
  t.equal(doc.has('#Foo'), false, here + 'original tags are untouched')
  const nums = nlp('tenho 1.234 euros')
  const c = nums.clone()
  c.numbers().add(1)
  t.equal(nums.text(), 'tenho 1.234 euros', here + 'numbers - original')
  t.equal(c.text(), 'tenho 1.235 euros', here + 'numbers - clone')
  const words = nlp('tenho vinte e um gatos')
  const w = words.clone()
  w.numbers().toNumber()
  t.equal(words.text(), 'tenho vinte e um gatos', here + 'number words - original')
  t.equal(w.text(), 'tenho 21 gatos', here + 'number words - clone')
  t.end()
})

