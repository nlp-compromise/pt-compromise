test('cache and freeze:', function (t) {
  const doc = nlp(txt)
  doc.cache()
  t.equal(doc.match('lições').text(), 'lições', here + 'word match on a cached doc')
  t.equal(doc.match('#Foo').found, false, here + 'tag match on a cached doc')
  doc.uncache()
  t.equal(doc.match('lições').text(), 'lições', here + 'uncache')
  const d = nlp('o sabiá dorme')
  d.match('sabiá').tag('Ave').freeze()
  d.match('sabiá').unTag('Ave')
  t.equal(d.match('sabiá').has('#Ave'), true, here + 'a frozen tag stays')
  d.unfreeze()
  d.match('sabiá').unTag('Ave')
  t.equal(d.match('sabiá').has('#Ave'), false, here + 'unfreeze')
  t.end()
})

test('contractions:', function (t) {
  const str = 'Vamos ao parque do irmão.'
  const doc = nlp(str)
  t.equal(doc.text(), str, here + 'text is unchanged')
  t.equal(doc.wordCount(), 5, here + 'wordCount counts the written words')
  t.equal(doc.terms().length, 7, here + 'ao and do are two terms each')
  t.equal(doc.match('a o parque').text(), 'ao parque', here + 'a o')
  t.equal(doc.match('de o irmão').text(), 'do irmão', here + 'de o')
  t.equal(doc.match('ao parque').found, true, here + 'ao')
  t.equal(doc.text('machine'), 'vamos a o parque de o irmão.', here + 'machine text')
  const json = doc.json()[0].terms
  t.equal(json[1].text, 'ao', here + 'json text')
  t.equal(json[1].implicit, 'a', here + 'json implicit')
  t.equal(json[2].implicit, 'o', here + 'json second half')
  // and its offset is still right
  const m = doc.match('parque').json({ offset: true })[0]
  t.equal(str.substr(m.offset.start, m.offset.length), 'parque', here + 'offset after a contraction')
  t.end()
})
